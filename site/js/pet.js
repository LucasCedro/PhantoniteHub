  /** Idle do estágio → cinza + X nos olhos (morte = forma atual, não ovo genérico). */
  function deadGridFor(stage) {
    const base = (SPRITES[stage] || SPRITES.larva).idle?.[0] || DEAD;
    const g = cloneGrid(base);
    const eyes = [];
    for (let y = 0; y < PX; y++) {
      for (let x = 0; x < PX; x++) {
        const c = g[y][x];
        if (c === 5) eyes.push([x, y]);
        if (c && c !== 1) g[y][x] = 6;
      }
    }
    const mark = (x, y) => {
      if (y >= 0 && y < PX && x >= 0 && x < PX) g[y][x] = 1;
    };
    if (eyes.length) {
      for (const [x, y] of eyes) {
        mark(x, y);
        mark(x + 1, y + 1);
        mark(x + 1, y);
        mark(x, y + 1);
      }
    } else {
      // fallback: X clássico perto do centro
      mark(5, 5);
      mark(6, 6);
      mark(6, 5);
      mark(5, 6);
      mark(9, 5);
      mark(10, 6);
      mark(10, 5);
      mark(9, 6);
    }
    return g;
  }

  /** Fecha olhos brancos (5→6) 1 frame — blink sem arte nova. */
  function blinkFrom(grid) {
    const g = cloneGrid(grid);
    for (let y = 0; y < PX; y++) {
      for (let x = 0; x < PX; x++) {
        if (g[y][x] === 5) g[y][x] = 6;
      }
    }
    return g;
  }

  /** Idle “hungry/sad”: olhos cinza + gota âmbar (sem frames novos). */
  function lowStatFrom(grid) {
    const g = cloneGrid(grid);
    let drop = false;
    for (let y = 0; y < PX; y++) {
      for (let x = 0; x < PX; x++) {
        const c = g[y][x];
        if (c === 5) g[y][x] = 6;
        // sparkles de chão viram preocupação
        if (c === 4 && y >= 10) g[y][x] = 7;
      }
    }
    // gota de suor no canto superior se houver espaço
    for (let y = 1; y < 5 && !drop; y++) {
      for (let x = 11; x < 15; x++) {
        if (!g[y][x] && !g[y + 1]?.[x]) {
          g[y][x] = 7;
          drop = true;
          break;
        }
      }
    }
    return g;
  }

